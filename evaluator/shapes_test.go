func TestColors(t *testing.T) {
	checkAll(t, []expectation{
		{"#3fa34d", "#3fa34d"},
		{"#3FA34D", "#3fa34d"},
		{"#f80", "#ff8800"},
		{"#3fa34d80", "#3fa34d80"},
		{"#3fa34dff", "#3fa34d"},
		{"#00000000", "#00000000"},
		{"type(#fff)", `"COLOR"`},
		{"#3fa34d.r", "63"},
		{"#3fa34d.g", "163"},
		{"#3fa34d.b", "77"},
		{"#3fa34d.a", "255"},
		{"#3fa34d80.a", "128"},
		{"type(#fff.r)", `"INTEGER"`},
		{"let c = #123; c.b", "51"},
		{"#fff == #ffffff", "true"},
		{"#fff === #ffffff", "true"},
		{"#fff == #fff", "true"},
		{"#fff == #ffffff00", "false"},
		{"#fff === #ffffff00", "false"},
		{"#fff != #000", "true"},
		{"#fff !== #fff", "false"},
		{"#fff == \"#ffffff\"", "false"},
		{"#fff == 1", "false"},
		{"#000 && #000", "true"},
		{"!#000", "false"},
		{"if (#000) { 1 } else { 2 }", "1"},
		{"[#f00, #0f0]", "[#ff0000, #00ff00]"},
		{"str(#abc)", `"#aabbcc"`},
		{"[#f00][0].r", "255"},
		{"#fff === #ffffff && #000 !== #001", "true"},
	})
}

